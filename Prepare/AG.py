# Функція для обчислення схеми Горнера та генерації текстової таблиці
def h(c, a):
    b = [c[0]]
    for i in range(1, len(c)): 
        b.append(c[i] + a * b[-1])
    t = " | ".join(f"{x:^5}" for x in c) + "\n" + " | ".join(f"{x:^5}" for x in b) + "\n"
    return b, t

